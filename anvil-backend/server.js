function connectionStringWithoutSslOverrides(connectionString) {
  let url;
  try {
    url = new URL(connectionString);
  } catch {
    throw new Error('DATABASE_URL must be a PostgreSQL connection URL.');
  }
  if (!['postgres:', 'postgresql:'].includes(url.protocol)) {
    throw new Error('DATABASE_URL must use the PostgreSQL protocol.');
  }
  for (const key of ['ssl', 'sslmode', 'sslcert', 'sslkey', 'sslrootcert']) {
    url.searchParams.delete(key);
  }
  return url.toString();
}

const pool = new Pool({
  connectionString: connectionStringWithoutSslOverrides(DATABASE_URL),
  ssl: { rejectUnauthorized: true },
  max: 5,
  connectionTimeoutMillis: 10000,
  idleTimeoutMillis: 30000,
});

pool.on('error', () => {
  console.error('Unexpected PostgreSQL idle client error.');
});

async function initializeDatabase() {
  await pool.query('SELECT 1');
  await pool.query(`
    CREATE TABLE IF NOT EXISTS trials (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    phone      TEXT NOT NULL,
    goal       TEXT NOT NULL,
    batch      TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'new',
    notes      TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
    )
  `);
  await pool.query('CREATE INDEX IF NOT EXISTS idx_trials_status ON trials(status)');
  await pool.query('CREATE INDEX IF NOT EXISTS idx_trials_created ON trials(created_at)');
  await pool.query('CREATE INDEX IF NOT EXISTS idx_trials_phone ON trials(phone)');
  await pool.query('CREATE INDEX IF NOT EXISTS idx_trials_phone_created ON trials(phone, created_at)');
}

