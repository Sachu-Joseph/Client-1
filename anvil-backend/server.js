app.get('/api/admin/trials', requireAdmin, asyncRoute(async (req, res) => {
  const status = String(req.query.status || '');
  const search = cleanText(req.query.q, 80);
  const where = [];
  const params = [];
  if (STATUSES.includes(status)) {
    params.push(status);
    where.push(`status = $${params.length}`);
  }
  if (search) {
    params.push(search);
    where.push(`(POSITION(lower($${params.length}) IN lower(name)) > 0
      OR POSITION(lower($${params.length}) IN lower(phone)) > 0)`);
  }
  const sql = `SELECT * FROM trials ${where.length ? 'WHERE ' + where.join(' AND ') : ''} ORDER BY created_at DESC LIMIT 500`;
  const [result, countResult] = await Promise.all([
    pool.query(sql, params),
    pool.query('SELECT status, COUNT(*)::INTEGER AS n FROM trials GROUP BY status'),
  ]);
  const counts = Object.fromEntries(STATUSES.map((s) => [s, 0]));
  for (const row of countResult.rows) counts[row.status] = row.n;
  res.json({ trials: result.rows, counts, statuses: STATUSES });
}));

app.patch('/api/admin/trials/:id', requireAdmin, asyncRoute(async (req, res) => {
  const id = Number(req.params.id);
  const result = Number.isSafeInteger(id)
    ? await pool.query('SELECT * FROM trials WHERE id = $1', [id])
    : { rows: [] };
  const row = result.rows[0];
  if (!row) return res.status(404).json({ error: 'Enquiry not found.' });

  const body = req.body || {};
  let status = row.status;
  let notes = row.notes;
  if (body.status !== undefined) {
    if (!STATUSES.includes(body.status)) return res.status(400).json({ error: 'Unknown status.' });
    status = body.status;
  }
  if (body.notes !== undefined) notes = String(body.notes).replace(/\u0000/g, '').slice(0, 1000);

  const updated = await pool.query(
    'UPDATE trials SET status = $1, notes = $2, updated_at = $3 WHERE id = $4 RETURNING *',
    [status, notes, new Date().toISOString(), id]
  );
  if (!updated.rowCount) return res.status(404).json({ error: 'Enquiry not found.' });
  res.json({ ok: true, trial: updated.rows[0] });
}));

