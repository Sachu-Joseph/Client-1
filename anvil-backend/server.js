let server;
let shuttingDown = false;
let shutdownPromise;

const HTTP_SHUTDOWN_TIMEOUT_MS = 8000;
const POOL_SHUTDOWN_TIMEOUT_MS = 2000;

function shutdown() {
  if (shutdownPromise) return shutdownPromise;
  shuttingDown = true;
  shutdownPromise = (async () => {
    let httpClosed = true;
    if (server) {
      httpClosed = await new Promise((resolve) => {
        const timeout = setTimeout(() => {
          server.closeAllConnections();
          resolve(false);
        }, HTTP_SHUTDOWN_TIMEOUT_MS);
        server.close((error) => {
          clearTimeout(timeout);
          if (error) console.error('HTTP server shutdown failed.');
          resolve(!error);
        });
      });
    }

    let poolTimeout;
    const poolClosed = await Promise.race([
      pool.end().then(
        () => true,
        () => {
          console.error('PostgreSQL pool shutdown failed.');
          return false;
        }
      ),
      new Promise((resolve) => {
        poolTimeout = setTimeout(() => resolve(false), POOL_SHUTDOWN_TIMEOUT_MS);
      }),
    ]);
    clearTimeout(poolTimeout);

    if (!httpClosed || !poolClosed) {
      console.error('Shutdown timed out before all resources closed.');
      process.exitCode = 1;
    }
    if (!poolClosed) process.exit(1);
  })();
  return shutdownPromise;
}

process.once('SIGINT', () => {
  shutdown().catch(() => {
    console.error('Shutdown failed.');
    process.exitCode = 1;
  });
});
process.once('SIGTERM', () => {
  shutdown().catch(() => {
    console.error('Shutdown failed.');
    process.exitCode = 1;
  });
});

async function start() {
  await initializeDatabase();
  if (shuttingDown) return;
  server = app.listen(PORT, () => {
    console.log(`Anvil backend running on port ${PORT}`);
    console.log(`Admin page: http://localhost:${PORT}/admin/`);
  });
  server.on('error', () => {
    console.error('HTTP server error.');
    shutdown();
  });
}

start().catch(() => {
  console.error('Failed to initialize the PostgreSQL database or start the server.');
  process.exitCode = 1;
  shutdown().catch(() => {
    console.error('Shutdown failed.');
    process.exitCode = 1;
  });
});

// ---------------------------------------------------------------------------
function loadDotEnv(file) {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    const value = m[2].replace(/^(['"])(.*)\1$/, '$2');
    if (process.env[m[1]] === undefined) process.env[m[1]] = value;
  }
}
