function cors(req, res, next) {
  const origin = req.headers.origin;
  if (origin) {
    const normalizedOrigin = origin.replace(/\/$/, '');
    const requestHost = req.headers.host;
    const sameHost = requestHost && normalizedOrigin === `${req.protocol}://${requestHost}`;
    const allowed = sameHost ||
      ALLOWED_ORIGINS.includes(normalizedOrigin) ||
      (!IS_PROD && !ALLOWED_ORIGINS.length);
    if (!allowed) return res.status(403).json({ error: 'This website is not allowed to send enquiries.' });
    res.setHeader('Access-Control-Allow-Origin', origin);
    res.setHeader('Vary', 'Origin');
    res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
    res.setHeader('Access-Control-Max-Age', '600');
  }
  if (req.method === 'OPTIONS') return res.sendStatus(204);
  next();
}

const submitLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  limit: 10,
  standardHeaders: 'draft-7',
  legacyHeaders: false,
  message: { error: 'Too many requests. Please try again in a few minutes.' },
});

function cleanText(value, max) {
  return String(value ?? '').replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}

// Accepts 10-digit Indian mobile numbers, with or without +91 / 91 / 0 in front.
function normalizePhone(raw) {
  let digits = String(raw ?? '').replace(/\D/g, '');
  if (digits.length === 12 && digits.startsWith('91')) digits = digits.slice(2);
  else if (digits.length === 11 && digits.startsWith('0')) digits = digits.slice(1);
  return /^[6-9]\d{9}$/.test(digits) ? digits : null;
}

app.options('/api/trials', cors);
app.post('/api/trials', cors, submitLimiter, asyncRoute(async (req, res) => {
  const body = req.body || {};

  // Hidden "website" field: real visitors leave it empty, bots fill it in.
  if (cleanText(body.website, 200)) return res.status(201).json({ ok: true });

  const name = cleanText(body.name, 80);
  const phone = normalizePhone(body.phone);
  const goal = cleanText(body.goal, 60);
  const batch = cleanText(body.batch, 60);

  if (name.length < 2) return res.status(400).json({ error: 'Enter your name.', field: 'name' });
  if (!phone) return res.status(400).json({ error: 'Enter a valid 10-digit mobile number.', field: 'phone' });
  if (!GOALS.includes(goal)) return res.status(400).json({ error: 'Choose a goal from the list.', field: 'goal' });
  if (!BATCHES.includes(batch)) return res.status(400).json({ error: 'Choose a batch from the list.', field: 'batch' });

  const client = await pool.connect();
  const dayAgo = new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString();
  let transactionStarted = false;
  let duplicate = false;
  try {
    await client.query('BEGIN');
    transactionStarted = true;
    await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1, 0))', [phone]);
    const recent = await client.query(
      'SELECT id FROM trials WHERE phone = $1 AND created_at >= $2 LIMIT 1',
      [phone, dayAgo]
    );
    if (recent.rowCount) {
      duplicate = true;
    } else {
      const now = new Date().toISOString();
      await client.query(
        `INSERT INTO trials (name, phone, goal, batch, created_at, updated_at)
         VALUES ($1, $2, $3, $4, $5, $5)`,
        [name, phone, goal, batch, now]
      );
    }
    await client.query('COMMIT');
  } catch (error) {
    if (transactionStarted) {
      try {
        await client.query('ROLLBACK');
      } catch {
        console.error('PostgreSQL transaction rollback failed.');
      }
    }
    throw error;
  } finally {
    client.release();
  }
  if (duplicate) return res.status(200).json({ ok: true, duplicate: true });
  res.status(201).json({ ok: true });
}));

